/**
 * invite.ts
 *
 * URL builders and query-string parsers for pre-filling the freelancer Stellar
 * address (and optional draft metadata) on `/post` via a shareable invite link
 * (issue #80).
 */

import { StrKey } from "@stellar/stellar-sdk";

export interface JobInviteParams {
  freelancer?: string;
  title?: string;
  asset?: string;
  inviteRequest?: boolean;
}

export interface ParsedJobInvite {
  /** Validated 56-character Stellar Ed25519 public key (`G...`), if present. */
  freelancer: string | null;
  /** Raw `freelancer` query value when present but invalid, so the UI can warn. */
  invalidFreelancer: string | null;
  title: string | null;
  asset: string | null;
  /** True when `?invite=1` was generated by a client requesting a freelancer's address. */
  inviteRequest: boolean;
}

export function isValidStellarAccount(address: string): boolean {
  const trimmed = address.trim();
  if (!trimmed) return false;
  try {
    return StrKey.isValidEd25519PublicKey(trimmed);
  } catch {
    return false;
  }
}

/**
 * Relative `/post?...` path pre-filling the freelancer address (and optional
 * job title / payment asset).
 */
export function buildJobInvitePath(params: JobInviteParams): string {
  const query = new URLSearchParams();
  if (params.freelancer && params.freelancer.trim()) {
    query.set("freelancer", params.freelancer.trim());
  }
  if (params.title && params.title.trim()) {
    query.set("title", params.title.trim());
  }
  if (params.asset && params.asset.trim()) {
    query.set("asset", params.asset.trim().toUpperCase());
  }
  if (params.inviteRequest) {
    query.set("invite", "1");
  }
  const qs = query.toString();
  return qs ? `/post?${qs}` : "/post";
}

/**
 * Absolute shareable invite URL anchored at `origin` (defaults to
 * `window.location.origin`).
 */
export function buildJobInviteUrl(
  params: JobInviteParams,
  origin?: string,
): string {
  const resolvedOrigin =
    origin ??
    (typeof window !== "undefined" && window.location?.origin
      ? window.location.origin
      : "http://localhost:5173");
  return `${resolvedOrigin.replace(/\/+$/, "")}${buildJobInvitePath(params)}`;
}

/**
 * Parse `/post` query parameters, validating `freelancer` as a real Stellar
 * Ed25519 `G...` public key before pre-filling the job form.
 */
export function parseJobInviteSearch(search?: string): ParsedJobInvite {
  const rawSearch =
    search ?? (typeof window !== "undefined" ? window.location.search : "");
  const params = new URLSearchParams(rawSearch);

  const rawFreelancer = params.get("freelancer")?.trim() ?? "";
  let freelancer: string | null = null;
  let invalidFreelancer: string | null = null;

  if (rawFreelancer) {
    if (isValidStellarAccount(rawFreelancer)) {
      freelancer = rawFreelancer;
    } else {
      invalidFreelancer = rawFreelancer;
    }
  }

  const rawTitle = params.get("title")?.trim() ?? "";
  const rawAsset = params.get("asset")?.trim().toUpperCase() ?? "";
  const inviteFlag = params.get("invite");

  return {
    freelancer,
    invalidFreelancer,
    title: rawTitle ? rawTitle.slice(0, 120) : null,
    asset: rawAsset || null,
    inviteRequest: inviteFlag === "1" || inviteFlag === "true",
  };
}
